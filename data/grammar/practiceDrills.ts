function gap(
  skill: GrammarPracticeSkill,
  id: string,
  stimulus: string,
  answer: string,
  distractors: DrillOptions,
  explanation: string,
  ruleAspect?: string,
  context?: string,
  prompt = "Complète la phrase avec la forme grammaticalement correcte.",
  contrastFamily?: GrammarContrastFamily,
): GrammarPracticeDrill {
  return {
    id,
    kind: "gap",
    skill,
    prompt,
    stimulus,
    displayLabel: "PHRASE À COMPLÉTER",
    ...(context ? { context } : {}),
    answer,
    distractors,
    explanation,
    ...(ruleAspect ? { ruleAspect } : {}),
    ...(contrastFamily ? { contrastFamily } : {}),
    ...(GRAMMAR_VOCABULARY_HINTS[id] ? { vocabulary: GRAMMAR_VOCABULARY_HINTS[id] } : {}),
  };
}

