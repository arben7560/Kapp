export function vocabularyCopyId(module: string, sourceText: string): string {
  return `${module}__${encodeURIComponent(sourceText).replace(/\./gu, "%2E")}`;
}

function buildVocabularyContent(locale: "fr" | "ja"): LocalizedModule {
  const content: Record<string, Record<string, string>> = {};
  for (const [module, entries] of Object.entries(VOCABULARY_COPY_BY_MODULE)) {
    for (const [sourceText, japaneseText] of Object.entries(entries)) {
      content[vocabularyCopyId(module, sourceText)] = {
        text: locale === "fr" ? sourceText : japaneseText,
      };
    }
  }
  return content;
}

