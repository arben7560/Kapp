export function immersionCopyId(module: string, sourceText: string): string {
  return module + "__" + encodeURIComponent(sourceText).replaceAll(".", "%2E");
}

function buildCafeCopy(locale: "fr" | "ja"): LocalizedModule {
  return Object.fromEntries(Object.entries(CAFE_IMMERSION_COPY).map(([source, ja]) => [
    immersionCopyId("cafe", source), { text: locale === "fr" ? source : ja },
  ]));
}

